#!/usr/bin/env python3
"""Generate tiny anti-aliased bitmap font atlases for Bordify OS."""

import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [
    ("font_ui_small", "DejaVuSans.ttf", 14),
    ("font_ui", "DejaVuSans.ttf", 17),
    ("font_ui_bold", "DejaVuSans-Bold.ttf", 16),
    ("font_title", "DejaVuSans-Bold.ttf", 21),
    ("font_h2", "DejaVuSans-Bold.ttf", 26),
    ("font_display", "DejaVuSans-Bold.ttf", 38),
]

SEARCH_DIRS = [
    "/usr/share/fonts/truetype/dejavu",
    "/usr/share/fonts/dejavu",
    "/usr/share/fonts/TTF",
]


def find_font(name):
    for directory in SEARCH_DIRS:
        path = os.path.join(directory, name)
        if os.path.isfile(path):
            return path
    raise FileNotFoundError("Could not find %s (install fonts-dejavu-core)" % name)


def c_array(data, per_line=24):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    return "\n".join(lines)


def emit_font(out, ident, ttf_name, pixel_size):
    path = find_font(ttf_name)
    font = ImageFont.truetype(path, pixel_size)
    ascent, descent = font.getmetrics()
    atlas = bytearray()
    glyphs = []
    padding = 3
    for code in range(32, 127):
        char = chr(code)
        advance = max(0, int(round(font.getlength(char))))
        box_width = max(1, advance + padding * 2 + 8)
        box_height = ascent + descent + padding * 2 + 4
        image = Image.new("L", (box_width, box_height), 0)
        draw = ImageDraw.Draw(image)
        draw.text((padding, padding + ascent), char, font=font, fill=255, anchor="ls")
        bbox = image.getbbox()
        if bbox is None:
            glyphs.append((len(atlas), 0, 0, 0, 0, advance))
            continue
        crop = image.crop(bbox)
        data = crop.tobytes()
        xoff = bbox[0] - padding
        yoff = bbox[1] - (padding + ascent)
        glyphs.append((len(atlas), crop.width, crop.height, xoff, yoff, advance))
        atlas.extend(data)

    out.append("/* Generated by tools/genfont.py. */")
    out.append("static const unsigned char %s_pixels[] = {" % ident)
    out.append(c_array(atlas) if atlas else "    0")
    out.append("};")
    out.append("static const glyph_t %s_glyphs[95] = {" % ident)
    for offset, width, height, xoff, yoff, advance in glyphs:
        out.append("    { %u, %u, %u, %d, %d, %u }," %
                   (offset, width, height, xoff, yoff, min(advance, 255)))
    out.append("};")
    out.append("const font_t %s = { %s_pixels, %s_glyphs, %u, %u };"
               % (ident, ident, ident, ascent + descent + 2, ascent))
    out.append("")


def main():
    output = sys.argv[1] if len(sys.argv) > 1 else "build/font.c"
    os.makedirs(os.path.dirname(output) or ".", exist_ok=True)
    out = ["#include \"font.h\"", ""]
    for ident, ttf_name, size in FONTS:
        emit_font(out, ident, ttf_name, size)
    with open(output, "w", encoding="ascii") as handle:
        handle.write("\n".join(out) + "\n")
    print("wrote", output)


if __name__ == "__main__":
    main()
